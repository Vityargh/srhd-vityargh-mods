import hashlib, json, pathlib, sys
sys.path.insert(0, r'S:\SR\python-tools')
import capstone, pefile
ROOT = pathlib.Path(__file__).parent
EXE = pathlib.Path(r'C:\Program Files (x86)\Steam\steamapps\common\Space Rangers HD A War Apart\Rangers.exe')
raw = EXE.read_bytes()
assert hashlib.sha256(raw).hexdigest() == 'e43a4b15503c705eebe2d8ce5778c2a2fb090db515a3fd86d319e5c5aa692ebf'
pe = pefile.PE(data=raw)
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
md.detail = True
entries = []
for name, addr in [('Kling',0x5b7284),('Warrior',0x5a5880),('Pirate',0x59d248),('Transport',0x5addc8),('Ranger',0x71931c),('Ruins',0x69dbc4),('Tranclucator',0x5b9e14),('DetonateGate',0x6d4098),('BeforeMovement',0x6e72b4),('StarPrepare',0x7e16e0),('StarDay',0x7f5698),('FireItem',0x6d1b2c),('FollowServiceGate',0x6e2e30),('HoleServiceGate',0x6e2828),('ServiceFuelRange',0x6d6e00),('ServiceJumpRange',0x6d6e6c),('ServiceTargetGate',0x7535b8),('ServiceDamageGate',0x6cd5e0),('ServiceHeatGate',0x6d2c58)]:
    code = pe.get_data(addr - pe.OPTIONAL_HEADER.ImageBase, 32)
    size = 0
    insns = []
    for i in md.disasm(code, addr):
        assert not i.group(capstone.CS_GRP_JUMP) and not i.group(capstone.CS_GRP_CALL)
        size += i.size
        insns.append(f'{i.mnemonic} {i.op_str}')
        if size >= 5: break
    entries.append(dict(name=name, address=addr, length=size, bytes=code[:size].hex(), instructions=insns))
# No whole-file hash: header edits (4GB/LAA flag, signatures, timestamps) must not block the mod.
# Instead every code location the plugin calls or reads is verified in memory at startup.
base = pe.OPTIONAL_HEADER.ImageBase
text = next(s for s in pe.sections if s.Name.rstrip(b'\0') == b'.text')
text_va = base + text.VirtualAddress
text_data = text.get_data()
anchors = []
for name, addr in [('usable',0x6d6768),('rangeOf',0x6d9f3c),('inSpace',0x6cbf48),('relation',0x6d42a4),
                   ('valueOf',0x6f5fb4),('player',0x747300),('serviceFire',0x6d1b2c)]:
    anchors.append((name, addr, pe.get_data(addr - base, 16)))
# Global data the plugin reads directly: anchor the first code sites that reference each address.
for name, addr in [('galaxySlot',0x81d2a0),('explosionRadius',0x81bb2c)]:
    needle = addr.to_bytes(4, 'little'); pos = 0; found = 0
    while found < 3:
        pos = text_data.find(needle, pos)
        if pos < 0: break
        start = max(0, pos - 4)
        anchors.append((f'{name}#{found}', text_va + start, text_data[start:start + 16])); found += 1; pos += 4
    assert found >= 1, f'no code reference to {name}'
header = '/* Generated by prepare.py. Byte anchors replace the old whole-file fingerprint. */\n'
header += 'static Patch patches[] = {\n'
for e in entries:
    b = ','.join('0x'+e['bytes'][i:i+2] for i in range(0,len(e['bytes']),2))
    header += f'{{0x{e["address"]:x}u,{e["length"]},{{{b}}}}}, /* {e["name"]} */\n'
header += '};\n'
header += '#define PATCH_COUNT (sizeof(patches)/sizeof(patches[0]))\n'
for label,addr in [('moveEntry',0x6e2560),('noneEntry',0x6e2534),('spawnEntry',0x738034),('listAddEntry',0x4161c0),('takeoffEntry',0x6e2968)]:
    header += 'static const unsigned char '+label+'[] = {'+','.join(hex(b) for b in pe.get_data(addr-pe.OPTIONAL_HEADER.ImageBase,16))+'};\n'
header += 'typedef struct { unsigned va; unsigned char b[16]; } Anchor;\nstatic const Anchor anchors[] = {\n'
for name, addr, data in anchors:
    header += '{0x%xu,{%s}}, /* %s */\n' % (addr, ','.join(hex(b) for b in data), name)
header += '};\n#define ANCHOR_COUNT (sizeof(anchors)/sizeof(anchors[0]))\n'
(ROOT/'signatures.h').write_text(header)
(ROOT/'binary-evidence.json').write_text(json.dumps(dict(sha256=hashlib.sha256(raw).hexdigest(),size=len(raw),hooks=entries,anchors=[dict(name=n,address=hex(a),bytes=d.hex()) for n,a,d in anchors]),indent=2))
abi={}
for name,addr,length in [('OrderNone',0x6e2534,41),('OrderMove',0x6e2560,94)]:
    code=pe.get_data(addr-pe.OPTIONAL_HEADER.ImageBase,length)
    abi[name]=dict(address=hex(addr),bytes=code.hex(),instructions=[f'{hex(i.address)} {i.mnemonic} {i.op_str}' for i in md.disasm(code,addr)])
assert 'mov esi, edx' in '\n'.join(abi['OrderMove']['instructions'])
assert 'mov ebx, ecx' in '\n'.join(abi['OrderMove']['instructions'])
assert 'test dl, dl' in '\n'.join(abi['OrderNone']['instructions'])
(ROOT/'navigation-abi-evidence.json').write_text(json.dumps(dict(exe_sha256=hashlib.sha256(raw).hexdigest(),abi=abi,contract='OrderMove: EAX=self, EDX=&PointF, CL=absolute; OrderNone: EAX=self, DL=override; both return with RET (no stack arguments)'),indent=2))
print(f'Verified executable SHA-256; decoded {len(entries)} complete hook prologues; OrderMove/OrderNone register ABI verified.')
